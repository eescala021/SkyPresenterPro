    nonisolated static func booksJSON() -> String {
        var items: [String] = []
        for book in books {
            items.append("{\"number\":\(book.0),\"name\":\"\(book.1)\",\"chapters\":\(book.2)}")
        }
        return "[" + items.joined(separator: ",") + "]"
    }

    nonisolated static func chaptersJSON(book bookNum: Int) -> String {
        let count = books.first(where: { $0.0 == bookNum })?.2 ?? 1
        let nums = (1...count).map { String($0) }.joined(separator: ",")
        return "[\(nums)]"
    }

    nonisolated static func versesJSON(book bookNum: Int, chapter: Int) -> String {
        let total: Int
        if let counts = verseCounts[bookNum], chapter >= 1, chapter <= counts.count {
            total = counts[chapter - 1]
        } else {
            total = 30
        }
        let items = (1...total).map { n in
            "{\"number\":\(n),\"text\":\"Versículo \(n).\"}"
        }
        return "[" + items.joined(separator: ",") + "]"
    }

